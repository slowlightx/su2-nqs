"""Finite physical space groups for periodic square and triangular lattices.

All site maps are active permutations, ``image[old_site] == new_site``.
This module is deliberately independent of exact-basis benchmarks: production
amplitude code may build an orbit without importing an ED/reference layer.
"""

from __future__ import annotations

import cmath
from collections.abc import Iterable, Mapping, Sequence
from functools import lru_cache
import math
from numbers import Integral

from .triangular_hnf import (
    C6,
    MX,
    hnf_character_numerators,
    hnf_point_group_permutations,
    hnf_site_permutation,
    hnf_translation_permutations,
    hnf_volume,
    matrix_vector,
    validate_hnf,
)


SitePermutation = tuple[int, ...]


def validate_site_permutation(
    image: Sequence[int], *, n_sites: int | None = None
) -> SitePermutation:
    """Return a checked active site permutation."""

    raw = tuple(image)
    if not raw:
        raise ValueError("a site permutation must be nonempty")
    if any(isinstance(site, bool) or not isinstance(site, Integral) for site in raw):
        raise TypeError("site-permutation entries must be integers")
    result = tuple(int(site) for site in raw)
    if n_sites is not None and len(result) != int(n_sites):
        raise ValueError("site permutation length does not match n_sites")
    if tuple(sorted(result)) != tuple(range(len(result))):
        raise ValueError("image must contain every site exactly once")
    return result


def inverse_site_permutation(image: Sequence[int]) -> SitePermutation:
    """Invert an active site permutation."""

    checked = validate_site_permutation(image)
    inverse = [0] * len(checked)
    for old, new in enumerate(checked):
        inverse[new] = old
    return tuple(inverse)


def compose_site_permutations(
    left: Sequence[int], right: Sequence[int]
) -> SitePermutation:
    """Return the active composition ``left o right``."""

    right_image = validate_site_permutation(right)
    left_image = validate_site_permutation(left, n_sites=len(right_image))
    return tuple(left_image[right_image[site]] for site in range(len(right_image)))


@lru_cache(maxsize=None)
def _validated_group_cached(
    images: tuple[SitePermutation, ...],
) -> tuple[SitePermutation, ...]:
    if not images:
        raise ValueError("a permutation group must be nonempty")
    n_sites = len(images[0])
    checked = tuple(
        validate_site_permutation(image, n_sites=n_sites) for image in images
    )
    if len(set(checked)) != len(checked):
        raise ValueError("group images must be duplicate free")
    elements = set(checked)
    if tuple(range(n_sites)) not in elements:
        raise ValueError("group images must contain the identity")
    for left in checked:
        for right in checked:
            # Both operands were checked above. Revalidating every integer
            # in both permutations for every product costs O(|G|^2 N)
            # Python type checks on large tori, without strengthening closure.
            # Retain the COMPLETE pairwise closure test, same composition.
            product = tuple(left[right[site]] for site in range(n_sites))
            if product not in elements:
                raise ValueError("group images are not closed under composition")
    return tuple(sorted(checked))


def validated_permutation_group(
    images: Iterable[Sequence[int]],
) -> tuple[SitePermutation, ...]:
    """Validate a duplicate-free finite group of physical site maps."""

    checked = tuple(validate_site_permutation(image) for image in images)
    return _validated_group_cached(checked)


def permutation_group_closure(
    generators: Iterable[Sequence[int]],
) -> tuple[SitePermutation, ...]:
    """Return the finite group generated by active site permutations."""

    checked = tuple(validate_site_permutation(image) for image in generators)
    if not checked:
        raise ValueError("at least one generator is required")
    n_sites = len(checked[0])
    if any(len(image) != n_sites for image in checked):
        raise ValueError("all generators must act on the same sites")
    identity = tuple(range(n_sites))
    seen = {identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in checked:
            candidate = compose_site_permutations(generator, current)
            if candidate not in seen:
                seen.add(candidate)
                frontier.append(candidate)
    return _validated_group_cached(tuple(sorted(seen)))


def _rectangular_image(rows: int, columns: int, transform) -> SitePermutation:
    result = []
    for row in range(rows):
        for column in range(columns):
            new_row, new_column = transform(row, column)
            result.append((new_row % rows) * columns + (new_column % columns))
    return validate_site_permutation(result, n_sites=rows * columns)


def rectangular_translation_group(
    rows: int, columns: int
) -> tuple[SitePermutation, ...]:
    """Return all translations of a periodic rectangular cell."""

    if (
        isinstance(rows, bool)
        or isinstance(columns, bool)
        or not isinstance(rows, Integral)
        or not isinstance(columns, Integral)
        or rows < 1
        or columns < 1
    ):
        raise ValueError("rows and columns must be positive integers")
    rows, columns = int(rows), int(columns)
    return validated_permutation_group(
        _rectangular_image(
            rows,
            columns,
            lambda row, column, dy=dy, dx=dx: (row + dy, column + dx),
        )
        for dy in range(rows)
        for dx in range(columns)
    )


def rectangular_translation_characters(
    rows: int,
    columns: int,
    momentum_row: int,
    momentum_column: int,
) -> tuple[complex, ...]:
    """Return momentum eigencharacters aligned with the translation group.

    Momentum is ``2*pi*(momentum_row/rows, momentum_column/columns)``.  For an
    active translation by ``(dy,dx)``, the returned physical eigenvalue is
    ``exp(-i*k.(dy,dx))``.  Passing this tuple to
    :class:`PhysicalSpatialProjector` therefore produces the coefficient
    ``conj(character)=exp(+i*k.t)`` in its Reynolds sum.
    """

    group = rectangular_translation_group(rows, columns)
    if any(
        isinstance(value, bool) or not isinstance(value, Integral)
        for value in (momentum_row, momentum_column)
    ):
        raise TypeError("momentum indices must be integers")
    rows, columns = int(rows), int(columns)
    momentum_row = int(momentum_row) % rows
    momentum_column = int(momentum_column) % columns
    values = []
    for image in group:
        dy, dx = divmod(image[0], columns)
        phase = -2.0 * math.pi * (
            momentum_row * dy / rows + momentum_column * dx / columns
        )
        values.append(cmath.exp(1.0j * phase))
    return tuple(values)


def rectangular_gamma_a1_group(
    rows: int, columns: int
) -> tuple[SitePermutation, ...]:
    """Return translations times every shape-preserving rectangular point map.

    A square cell retains ``D4``.  A nonsquare rectangle retains its ``D2``
    subgroup, with accidental duplicate maps on length-two directions removed
    by the group closure.
    """

    translations = rectangular_translation_group(rows, columns)
    rows, columns = int(rows), int(columns)
    generators: list[SitePermutation] = [translations[1]] if len(translations) > 1 else []
    generators.extend(
        [
            _rectangular_image(rows, columns, lambda row, column: (-row, -column)),
            _rectangular_image(rows, columns, lambda row, column: (row, -column)),
        ]
    )
    # Supplying all translations avoids relying on their sorted order to pick
    # primitive generators on thin or tilted-looking cells.
    generators.extend(translations)
    if rows == columns:
        generators.append(
            _rectangular_image(rows, columns, lambda row, column: (-column, row))
        )
    return permutation_group_closure(generators)


def square_gamma_a1_group(linear_size: int) -> tuple[SitePermutation, ...]:
    """Return the translation-by-D4 group of a square torus."""

    return rectangular_gamma_a1_group(linear_size, linear_size)


def triangular_hnf_gamma_a1_group(
    supercell: tuple[tuple[int, int], tuple[int, int]],
) -> tuple[SitePermutation, ...]:
    """Return translations times full D6 for a compatible triangular HNF torus."""

    matrix = validate_hnf(supercell)
    return permutation_group_closure(
        (
            hnf_site_permutation(matrix, translation=(1, 0)),
            hnf_site_permutation(matrix, translation=(0, 1)),
            hnf_site_permutation(matrix, operation=C6),
            hnf_site_permutation(matrix, operation=MX),
        )
    )


def triangular_hnf_translation_group(
    supercell: tuple[tuple[int, int], tuple[int, int]],
) -> tuple[SitePermutation, ...]:
    """Return every physical translation of a triangular HNF torus."""

    matrix = validate_hnf(supercell)
    return validated_permutation_group(
        image for _, image in hnf_translation_permutations(matrix)
    )


def triangular_hnf_reciprocal_little_group(
    supercell: tuple[tuple[int, int], tuple[int, int]],
    momentum_numerator: tuple[int, int],
) -> tuple[str, ...]:
    """Return retained point operations fixing one exact HNF momentum.

    The momentum is represented as ``2*pi*momentum_numerator/N``, where
    ``N`` is the HNF volume.  Stabilizer membership is decided with integer
    arithmetic, never floating-point phases.  Only point operations retained
    by the *finite torus* are considered; this distinction is essential on a
    nonsquare ``6 x 3`` triangular cell, which retains ``C2v`` rather than the
    infinite lattice's full ``D6``.
    """

    matrix = validate_hnf(supercell)
    if (
        len(momentum_numerator) != 2
        or any(
            isinstance(value, bool) or not isinstance(value, Integral)
            for value in momentum_numerator
        )
    ):
        raise TypeError("momentum_numerator must contain two integers")
    volume = hnf_volume(matrix)
    numerator = tuple(int(value) % volume for value in momentum_numerator)
    if numerator not in hnf_character_numerators(matrix):
        raise ValueError("momentum_numerator is not an HNF quotient character")

    primitive = ((1, 0), (0, 1))
    return tuple(
        name
        for name, operation, _ in hnf_point_group_permutations(matrix)
        if all(
            sum(
                numerator[axis]
                * (matrix_vector(operation, vector)[axis] - vector[axis])
                for axis in range(2)
            )
            % volume
            == 0
            for vector in primitive
        )
    )


def triangular_hnf_little_space_group_character(
    supercell: tuple[tuple[int, int], tuple[int, int]],
    momentum_numerator: tuple[int, int],
    point_characters: Mapping[str, complex],
) -> tuple[tuple[SitePermutation, ...], tuple[complex, ...]]:
    """Build a one-dimensional character of an HNF little space group.

    The returned permutation and character tuples are aligned and can be
    passed directly to :class:`su2_nqs.models.spatial_projector.PhysicalSpatialProjector`.
    For the active affine action ``r -> p*r+t``, the eigencharacter is

    ``exp(-2*pi*i*momentum_numerator.t/N) * point_characters[p]``.

    This helper deliberately fails closed if the requested point characters
    do not form a one-dimensional representation of the actual finite
    little group.  Operations moving the momentum to a different star arm
    are excluded; projecting a full star requires a multidimensional sewing
    representation and is outside this scalar-character API.
    """

    matrix = validate_hnf(supercell)
    volume = hnf_volume(matrix)
    little_names = triangular_hnf_reciprocal_little_group(
        matrix, momentum_numerator
    )
    supplied = {str(name): complex(value) for name, value in point_characters.items()}
    if set(supplied) != set(little_names):
        raise ValueError(
            "point_characters must cover exactly the retained reciprocal little group"
        )
    if any(
        not math.isfinite(value.real)
        or not math.isfinite(value.imag)
        or abs(abs(value) - 1.0) > 1.0e-10
        for value in supplied.values()
    ):
        raise ValueError("point characters must be finite and have unit modulus")

    numerator = tuple(int(value) % volume for value in momentum_numerator)
    point_entries = {
        name: (operation, image)
        for name, operation, image in hnf_point_group_permutations(matrix)
        if name in little_names
    }
    character_by_image: dict[SitePermutation, complex] = {}
    for translation, _ in hnf_translation_permutations(matrix):
        translation_phase = cmath.exp(
            -2.0j
            * math.pi
            * (
                numerator[0] * translation[0]
                + numerator[1] * translation[1]
            )
            / volume
        )
        for name in little_names:
            operation, _ = point_entries[name]
            image = hnf_site_permutation(
                matrix, translation=translation, operation=operation
            )
            character = translation_phase * supplied[name]
            previous = character_by_image.get(image)
            if previous is not None and abs(previous - character) > 1.0e-10:
                raise ValueError(
                    "requested character is inconsistent on the finite affine-group image"
                )
            character_by_image[image] = character

    group = validated_permutation_group(character_by_image)
    characters = tuple(character_by_image[image] for image in group)
    index_by_image = {image: index for index, image in enumerate(group)}
    for left_index, left in enumerate(group):
        for right_index, right in enumerate(group):
            product = compose_site_permutations(left, right)
            product_index = index_by_image[product]
            if abs(
                characters[product_index]
                - characters[left_index] * characters[right_index]
            ) > 1.0e-10:
                raise ValueError(
                    "point_characters do not define a one-dimensional little-group representation"
                )
    return group, characters


def triangular_hnf_retained_gamma_a1_group(
    supercell: tuple[tuple[int, int], tuple[int, int]],
) -> tuple[SitePermutation, ...]:
    """Return translations times every point map retained by an HNF torus.

    Unlike :func:`triangular_hnf_gamma_a1_group`, this function does not
    require the finite cell to retain the full triangular ``D6`` point group.
    It is therefore the honest A1/trivial-character projector for rectangular
    or tilted finite tori.  The retained point-group order must be reported
    with benchmark results; e.g. the ``4 x 6`` rectangular HNF keeps only
    ``C2`` and hence has space-group image order ``24 * 2 = 48``.
    """

    matrix = validate_hnf(supercell)
    translations = tuple(
        image for _, image in hnf_translation_permutations(matrix)
    )
    point_images = tuple(
        image for _, _, image in hnf_point_group_permutations(matrix)
    )
    return permutation_group_closure((*translations, *point_images))


