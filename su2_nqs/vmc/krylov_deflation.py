"""Low-rank global coarse corrections for matrix-free Fisher solves.

The physical Fisher block inverse captures correlations *within* a local
carrier coordinate.  It deliberately discards correlations between those
coordinates.  This module restores a bounded number of global directions by
building an Arnoldi space of the block-preconditioned normal operator and
using the symmetric two-level inverse

.. math::

   Q B Q^T + Z (Z^T A Z)^{-1} Z^T,

where ``B`` is the local block inverse and
``Q = I - Z (Z^T A Z)^{-1} Z^T A``.  The implementation stores ``O(P r)``
numbers for ``P`` parameters and coarse rank ``r``; it never materializes a
``P x P`` Fisher matrix.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import NamedTuple

import jax
import jax.numpy as jnp


class DeflatedPreconditioner(NamedTuple):
    """Symmetric two-level inverse represented by a row-oriented basis."""

    basis: jax.Array
    normal_images: jax.Array
    coarse_inverse: jax.Array
    active_rank: jax.Array
    minimum_coarse_eigenvalue: jax.Array
    maximum_coarse_eigenvalue: jax.Array

    def apply(
        self,
        vector: jax.Array,
        base_preconditioner: Callable[[jax.Array], jax.Array],
    ) -> jax.Array:
        """Apply the SPD two-level inverse to a flat real vector."""

        coefficients = self.coarse_inverse @ (self.basis @ vector)
        projected = vector - self.normal_images.T @ coefficients
        fine = base_preconditioner(projected)
        fine_coefficients = self.coarse_inverse @ (
            self.normal_images @ fine
        )
        return (
            fine
            - self.basis.T @ fine_coefficients
            + self.basis.T @ coefficients
        )

    __call__ = apply

    @property
    def stored_matrix_elements(self) -> int:
        """Number of stored scalars, excluding the base preconditioner."""

        return int(
            self.basis.size
            + self.normal_images.size
            + self.coarse_inverse.size
        )


def build_arnoldi_deflated_preconditioner(
    matvec: Callable[[jax.Array], jax.Array],
    rhs: jax.Array,
    base_preconditioner: Callable[[jax.Array], jax.Array],
    *,
    rank: int,
) -> DeflatedPreconditioner:
    """Build a direction-adapted global coarse space of ``B A``.

    The first vector is the normalized block-preconditioned right-hand side.
    Subsequent vectors are generated by twice-reorthogonalized Arnoldi steps.
    Exact normal images are retained, so the coarse operator is the symmetric
    Ritz matrix ``Z.T @ A @ Z`` even though ``B A`` is not Euclidean-symmetric.

    A rank-deficient space is handled by a spectral pseudoinverse.  With a
    damped positive-definite normal operator, every nonzero Arnoldi vector has
    strictly positive coarse curvature.
    """

    if rank < 1:
        raise ValueError("Arnoldi deflation rank must be positive")
    vector = jnp.asarray(rhs)
    if vector.ndim != 1:
        raise ValueError("Arnoldi deflation requires a flat right-hand side")
    if not jnp.issubdtype(vector.dtype, jnp.floating):
        raise TypeError("Arnoldi deflation requires a real floating right-hand side")
    if rank > vector.size:
        raise ValueError("Arnoldi deflation rank may not exceed parameter count")

    tiny = jnp.sqrt(jnp.finfo(vector.dtype).eps)
    first = base_preconditioner(vector)
    first_norm = jnp.linalg.norm(first)
    first_active = jnp.isfinite(first_norm) & (first_norm > tiny)
    first = jnp.where(first_active, first / jnp.maximum(first_norm, tiny), 0.0)
    basis = jnp.zeros((rank, vector.size), dtype=vector.dtype).at[0].set(first)
    normal_images = jnp.zeros_like(basis)
    active = jnp.zeros((rank,), dtype=jnp.bool_).at[0].set(first_active)

    def arnoldi_step(index, state):
        current_basis, current_images, current_active = state
        direction = current_basis[index]
        normal_image = matvec(direction)
        current_images = current_images.at[index].set(normal_image)
        candidate = base_preconditioner(normal_image)
        used = (jnp.arange(rank) <= index).astype(vector.dtype)
        # Two modified-Gram-Schmidt passes are important for the very
        # anisotropic damped Fisher systems encountered at N=16.
        for _ in range(2):
            overlaps = (current_basis @ candidate) * used
            candidate = candidate - overlaps @ current_basis
        candidate_norm = jnp.linalg.norm(candidate)
        candidate_active = (
            jnp.isfinite(candidate_norm)
            & (candidate_norm > tiny)
            & current_active[index]
        )
        candidate = jnp.where(
            candidate_active,
            candidate / jnp.maximum(candidate_norm, tiny),
            0.0,
        )
        target = jnp.minimum(index + 1, rank - 1)
        proposed_basis = current_basis.at[target].set(candidate)
        proposed_active = current_active.at[target].set(candidate_active)
        current_basis = jax.lax.cond(
            index + 1 < rank,
            lambda _: proposed_basis,
            lambda _: current_basis,
            operand=None,
        )
        current_active = jax.lax.cond(
            index + 1 < rank,
            lambda _: proposed_active,
            lambda _: current_active,
            operand=None,
        )
        return current_basis, current_images, current_active

    basis, normal_images, active = jax.lax.fori_loop(
        0,
        rank,
        arnoldi_step,
        (basis, normal_images, active),
    )
    coarse = basis @ normal_images.T
    coarse = 0.5 * (coarse + coarse.T)
    eigenvalues, eigenvectors = jnp.linalg.eigh(coarse)
    scale = jnp.maximum(jnp.max(jnp.abs(eigenvalues)), 1.0)
    spectral_floor = 64.0 * jnp.finfo(vector.dtype).eps * scale
    retained = eigenvalues > spectral_floor
    inverse_eigenvalues = jnp.where(retained, 1.0 / eigenvalues, 0.0)
    coarse_inverse = (eigenvectors * inverse_eigenvalues[None, :]) @ eigenvectors.T
    positive_values = jnp.where(retained, eigenvalues, jnp.inf)
    minimum = jnp.min(positive_values)
    minimum = jnp.where(jnp.any(retained), minimum, 0.0)
    maximum = jnp.max(jnp.where(retained, eigenvalues, 0.0))
    return DeflatedPreconditioner(
        basis=basis,
        normal_images=normal_images,
        coarse_inverse=coarse_inverse,
        active_rank=jnp.minimum(jnp.sum(active), jnp.sum(retained)),
        minimum_coarse_eigenvalue=minimum,
        maximum_coarse_eigenvalue=maximum,
    )


__all__ = [
    "DeflatedPreconditioner",
    "build_arnoldi_deflated_preconditioner",
]
