"""Strict computational-basis ``Gamma.A1`` singlet-AGP reference carrier.

This module is deliberately separate from the fusion-NQS models.  It provides
an exact-small feasibility reference for an alternative variational carrier:

* a number- and Gutzwiller-projected spin-singlet AGP amplitude in the
  computational spin basis; and
* a Reynolds average over *physical* site permutations in that same basis.

The result is an exact total-spin singlet in the trivial spatial irrep (up to
floating-point roundoff).  It is not an autoregressive normalized state and it
does not establish a scaling advantage for a fusion-path NQS.

Bits follow the repository convention: ``0`` is spin down, ``1`` is spin up,
and site zero is the most-significant computational bit.  Site permutations
are active maps ``image[old_site] == new_site``.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass
from functools import lru_cache
from math import comb
from numbers import Integral

import numpy as np

from ..lattices.square_symmetry import square_site_generators
from ..lattices.triangular_hnf import (
    C6,
    MX,
    hnf_site_permutation,
    validate_hnf,
)
from ..operators.sz_heisenberg import SzHeisenbergGraph


SpinConfiguration = tuple[int, ...]
SitePermutation = tuple[int, ...]
GraphBond = tuple[int, int, float]
SpinAmplitude = Callable[[SpinConfiguration], complex]


def _validated_binary_configuration(
    configuration: Sequence[int],
    *,
    n_sites: int | None = None,
) -> SpinConfiguration:
    raw = tuple(configuration)
    if not raw or any(
        isinstance(bit, bool)
        or not isinstance(bit, Integral)
        or int(bit) not in (0, 1)
        for bit in raw
    ):
        raise ValueError("configuration must be a nonempty binary sequence")
    result = tuple(int(bit) for bit in raw)
    if n_sites is not None and len(result) != int(n_sites):
        raise ValueError("configuration length does not match the number of sites")
    return result


def _validated_half_filled_configuration(
    configuration: Sequence[int],
    *,
    n_sites: int | None = None,
) -> SpinConfiguration:
    result = _validated_binary_configuration(configuration, n_sites=n_sites)
    if len(result) % 2 or sum(result) != len(result) // 2:
        raise ValueError("a singlet AGP amplitude requires even N and N/2 up spins")
    return result


def _validated_site_permutation(
    image: Sequence[int],
    *,
    n_sites: int | None = None,
) -> SitePermutation:
    raw = tuple(image)
    if not raw:
        raise ValueError("a site permutation must be nonempty")
    if any(
        isinstance(site, bool) or not isinstance(site, Integral)
        for site in raw
    ):
        raise TypeError("site-permutation entries must be integers")
    result = tuple(int(site) for site in raw)
    if n_sites is not None and len(result) != int(n_sites):
        raise ValueError("site permutation length does not match the number of sites")
    if tuple(sorted(result)) != tuple(range(len(result))):
        raise ValueError("image must contain every site exactly once")
    return result


def compose_site_permutations(
    left: Sequence[int], right: Sequence[int]
) -> SitePermutation:
    """Return the active composition ``left o right``.

    Both inputs obey ``image[old] == new``.  Hence the composed image is
    ``left[right[old]]``.
    """

    right_image = _validated_site_permutation(right)
    left_image = _validated_site_permutation(left, n_sites=len(right_image))
    return tuple(left_image[right_image[site]] for site in range(len(right_image)))


def permutation_group_closure(
    generators: Iterable[Sequence[int]],
) -> tuple[SitePermutation, ...]:
    """Return the finite physical permutation group generated by ``generators``."""

    checked = tuple(_validated_site_permutation(image) for image in generators)
    if not checked:
        raise ValueError("at least one site-permutation generator is required")
    n_sites = len(checked[0])
    if any(len(image) != n_sites for image in checked):
        raise ValueError("all generators must act on the same sites")

    identity = tuple(range(n_sites))
    seen = {identity}
    frontier = [identity]
    while frontier:
        current = frontier.pop()
        for generator in checked:
            candidate = tuple(
                generator[current[site]] for site in range(n_sites)
            )
            if candidate not in seen:
                seen.add(candidate)
                frontier.append(candidate)
    return _validated_permutation_group_cached(tuple(sorted(seen)))


@lru_cache(maxsize=None)
def _validated_permutation_group_cached(
    group_images: tuple[SitePermutation, ...],
) -> tuple[SitePermutation, ...]:
    if not group_images:
        raise ValueError("group_images must be nonempty")
    n_sites = len(group_images[0])
    checked = tuple(
        _validated_site_permutation(image, n_sites=n_sites)
        for image in group_images
    )
    if len(set(checked)) != len(checked):
        raise ValueError("group_images must not contain duplicate physical maps")
    identity = tuple(range(n_sites))
    elements = set(checked)
    if identity not in elements:
        raise ValueError("group_images must contain the identity")
    for left in checked:
        for right in checked:
            product = tuple(left[right[site]] for site in range(n_sites))
            if product not in elements:
                raise ValueError("group_images are not closed under composition")
    return tuple(sorted(checked))


def validated_permutation_group(
    group_images: Iterable[Sequence[int]],
) -> tuple[SitePermutation, ...]:
    """Validate a duplicate-free finite group of active site permutations."""

    raw = tuple(_validated_site_permutation(image) for image in group_images)
    return _validated_permutation_group_cached(raw)


def square_gamma_a1_group(linear_size: int) -> tuple[SitePermutation, ...]:
    """Return the physical translation-by-D4 image group of a square torus."""

    generators = square_site_generators(linear_size)
    return permutation_group_closure(
        generators[name] for name in ("tx", "ty", "c4", "mx")
    )


def triangular_hnf_gamma_a1_group(
    supercell: tuple[tuple[int, int], tuple[int, int]],
) -> tuple[SitePermutation, ...]:
    """Return the physical translation-by-D6 image group of an HNF torus.

    This fails closed when the finite torus does not retain either requested
    point-group generator; it never silently replaces full D6 by a subgroup.
    """

    matrix = validate_hnf(supercell)
    generators = (
        hnf_site_permutation(matrix, translation=(1, 0)),
        hnf_site_permutation(matrix, translation=(0, 1)),
        hnf_site_permutation(matrix, operation=C6),
        hnf_site_permutation(matrix, operation=MX),
    )
    return permutation_group_closure(generators)


def pullback_spin_configuration(
    configuration: Sequence[int], image: Sequence[int]
) -> SpinConfiguration:
    """Return the source configuration in ``(U_image psi)(sigma)``.

    For the active convention ``image[old] == new``, the source bit at an old
    site is the target bit at ``image[old]``.  No fermionic permutation sign is
    present: this is the physical tensor-product spin representation.
    """

    target = _validated_binary_configuration(configuration)
    checked_image = _validated_site_permutation(image, n_sites=len(target))
    return tuple(target[checked_image[old]] for old in range(len(target)))


def site_order_fermionic_sign(configuration: Sequence[int]) -> int:
    """Sign for reordering all-up/all-down creators into physical site order.

    The determinant groups occupied modes as all up sites followed by all down
    sites.  The physical spin basis instead orders the one occupied mode on
    each site by increasing site.  Their relative parity is
    ``(-1)**I``, where ``I`` counts down sites lying to the left of up sites.
    """

    checked = _validated_binary_configuration(configuration)
    down_to_left = 0
    inversions = 0
    for bit in checked:
        if bit == 0:
            down_to_left += 1
        else:
            inversions += down_to_left
    return -1 if inversions % 2 else 1


def _validated_pairing_matrix(
    pairing: np.ndarray | Sequence[Sequence[complex]],
    *,
    symmetry_tolerance: float,
) -> np.ndarray:
    if not np.isfinite(symmetry_tolerance) or symmetry_tolerance <= 0.0:
        raise ValueError("symmetry_tolerance must be finite and positive")
    matrix = np.asarray(pairing, dtype=np.complex128)
    if matrix.ndim != 2 or matrix.shape[0] != matrix.shape[1]:
        raise ValueError("pairing must be a square matrix")
    n_sites = matrix.shape[0]
    if n_sites < 2 or n_sites % 2:
        raise ValueError("pairing dimension must be a positive even site count")
    if np.any(~np.isfinite(matrix.real)) or np.any(~np.isfinite(matrix.imag)):
        raise ValueError("pairing entries must be finite")
    scale = max(float(np.max(np.abs(matrix))), 1.0)
    if float(np.max(np.abs(matrix - matrix.T))) > symmetry_tolerance * scale:
        raise ValueError("spin-singlet pairing must be symmetric under transpose")
    if float(np.max(np.abs(np.diag(matrix)))) > symmetry_tolerance * scale:
        raise ValueError(
            "onsite pairing is removed by the one-particle-per-site projection; "
            "supply a zero diagonal"
        )
    # Make the defining algebraic constraints exact in the stored floating
    # representation after accepting only roundoff-size input discrepancies.
    result = 0.5 * (matrix + matrix.T)
    np.fill_diagonal(result, 0.0)
    result = np.array(result, dtype=np.complex128, copy=True)
    result.setflags(write=False)
    return result


def _agp_determinant_unchecked(
    configuration: SpinConfiguration, pairing: np.ndarray
) -> complex:
    up = tuple(site for site, bit in enumerate(configuration) if bit == 1)
    down = tuple(site for site, bit in enumerate(configuration) if bit == 0)
    pair_count = len(up)
    block = pairing[np.ix_(up, down)]
    block_pfaffian_sign = -1 if (pair_count * (pair_count - 1) // 2) % 2 else 1
    return complex(
        block_pfaffian_sign
        * site_order_fermionic_sign(configuration)
        * np.linalg.det(block)
    )


def singlet_agp_determinant_amplitude(
    configuration: Sequence[int],
    pairing: np.ndarray | Sequence[Sequence[complex]],
    *,
    symmetry_tolerance: float = 1.0e-12,
) -> complex:
    r"""Return a Gutzwiller-projected spin-singlet AGP amplitude.

    For sorted up/down site sets ``U,D`` and ``n=N/2``, the convention is

    ``psi(sigma) = (-1)^(I(sigma)+n(n-1)/2) det(F[U,D])``.

    Here ``I`` counts pairs ``(d,u)`` with ``d<u``.  The second sign is the
    Pfaffian-to-determinant sign of the all-up/all-down block order.  Together
    they match a site-major fermionic embedding and give
    ``|up,down> - |down,up>`` for a positive two-site pairing.
    """

    checked_pairing = _validated_pairing_matrix(
        pairing, symmetry_tolerance=symmetry_tolerance
    )
    checked_configuration = _validated_half_filled_configuration(
        configuration, n_sites=checked_pairing.shape[0]
    )
    return _agp_determinant_unchecked(checked_configuration, checked_pairing)


def _recursive_pfaffian(matrix: np.ndarray) -> complex:
    dimension = matrix.shape[0]
    if dimension == 0:
        return 1.0 + 0.0j
    answer = 0.0 + 0.0j
    for partner in range(1, dimension):
        remainder = tuple(
            index for index in range(1, dimension) if index != partner
        )
        submatrix = matrix[np.ix_(remainder, remainder)]
        sign = 1 if partner % 2 else -1
        answer += sign * matrix[0, partner] * _recursive_pfaffian(submatrix)
    return complex(answer)


def singlet_agp_pfaffian_reference(
    configuration: Sequence[int],
    pairing: np.ndarray | Sequence[Sequence[complex]],
    *,
    symmetry_tolerance: float = 1.0e-12,
    maximum_sites: int = 12,
) -> complex:
    """Independent exponential Pfaffian reference for the determinant sign.

    The occupied modes are ordered site-major as ``(site-up, site-down)`` and
    exactly one mode is retained per site.  This routine is only a sign oracle;
    scalable evaluation must use :func:`singlet_agp_determinant_amplitude`.
    """

    checked_pairing = _validated_pairing_matrix(
        pairing, symmetry_tolerance=symmetry_tolerance
    )
    n_sites = checked_pairing.shape[0]
    if (
        isinstance(maximum_sites, bool)
        or not isinstance(maximum_sites, Integral)
        or int(maximum_sites) < 2
    ):
        raise ValueError("maximum_sites must be an integer at least two")
    if n_sites > int(maximum_sites):
        raise ValueError("Pfaffian reference exceeds the exact-small site cap")
    checked_configuration = _validated_half_filled_configuration(
        configuration, n_sites=n_sites
    )

    spin_orbital = np.zeros((2 * n_sites, 2 * n_sites), dtype=np.complex128)
    for up_site in range(n_sites):
        for down_site in range(n_sites):
            value = checked_pairing[up_site, down_site]
            up_mode = 2 * up_site
            down_mode = 2 * down_site + 1
            spin_orbital[up_mode, down_mode] = value
            spin_orbital[down_mode, up_mode] = -value
    occupied = tuple(
        2 * site + (0 if bit == 1 else 1)
        for site, bit in enumerate(checked_configuration)
    )
    return _recursive_pfaffian(spin_orbital[np.ix_(occupied, occupied)])


def reynolds_projected_amplitude(
    configuration: Sequence[int],
    base_amplitude: SpinAmplitude,
    group_images: Iterable[Sequence[int]],
) -> complex:
    """Apply the trivial-character Reynolds projector to one amplitude row."""

    checked_configuration = _validated_binary_configuration(configuration)
    group = validated_permutation_group(group_images)
    if len(group[0]) != len(checked_configuration):
        raise ValueError("group and configuration act on different site counts")
    total = 0.0 + 0.0j
    for image in group:
        source = tuple(
            checked_configuration[image[old]]
            for old in range(len(checked_configuration))
        )
        total += complex(base_amplitude(source))
    return total / len(group)


@dataclass(frozen=True)
class ProjectedSingletAGP:
    """One exact-singlet AGP with a physical ``Gamma.A1`` Reynolds average."""

    pairing: np.ndarray
    group_images: tuple[SitePermutation, ...]
    symmetry_tolerance: float = 1.0e-12

    def __post_init__(self) -> None:
        checked_pairing = _validated_pairing_matrix(
            self.pairing, symmetry_tolerance=self.symmetry_tolerance
        )
        group = validated_permutation_group(self.group_images)
        if len(group[0]) != checked_pairing.shape[0]:
            raise ValueError("pairing and group act on different site counts")
        object.__setattr__(self, "pairing", checked_pairing)
        object.__setattr__(self, "group_images", group)

    @property
    def n_sites(self) -> int:
        return int(self.pairing.shape[0])

    @property
    def pair_count(self) -> int:
        return self.n_sites // 2

    @property
    def group_order(self) -> int:
        return len(self.group_images)

    def base_amplitude(self, configuration: Sequence[int]) -> complex:
        checked = _validated_half_filled_configuration(
            configuration, n_sites=self.n_sites
        )
        return _agp_determinant_unchecked(checked, self.pairing)

    def amplitude(self, configuration: Sequence[int]) -> complex:
        checked = _validated_half_filled_configuration(
            configuration, n_sites=self.n_sites
        )
        total = 0.0 + 0.0j
        for image in self.group_images:
            source = tuple(checked[image[old]] for old in range(self.n_sites))
            total += _agp_determinant_unchecked(source, self.pairing)
        return total / self.group_order

    def __call__(self, configuration: Sequence[int]) -> complex:
        return self.amplitude(configuration)

    def amplitudes(
        self, configurations: Iterable[Sequence[int]]
    ) -> np.ndarray:
        return np.asarray(
            [self.amplitude(configuration) for configuration in configurations],
            dtype=np.complex128,
        )

    def hamiltonian_action(
        self,
        configuration: Sequence[int],
        bonds: Iterable[Sequence[float]],
    ) -> complex:
        return heisenberg_hpsi_amplitude(self, configuration, bonds)


@dataclass(frozen=True)
class ProjectedSingletAGPCombination:
    """A strict linear combination of compatible projected AGP carriers."""

    carriers: tuple[ProjectedSingletAGP, ...]
    coefficients: np.ndarray

    def __post_init__(self) -> None:
        carriers = tuple(self.carriers)
        if not carriers or any(
            not isinstance(carrier, ProjectedSingletAGP) for carrier in carriers
        ):
            raise TypeError("carriers must be nonempty ProjectedSingletAGP instances")
        reference = carriers[0]
        if any(carrier.n_sites != reference.n_sites for carrier in carriers):
            raise ValueError("all carriers must have the same site count")
        if any(carrier.group_images != reference.group_images for carrier in carriers):
            raise ValueError("all carriers must use the same physical projector")
        coefficients = np.asarray(self.coefficients, dtype=np.complex128)
        if coefficients.shape != (len(carriers),):
            raise ValueError("coefficients must contain one scalar per carrier")
        if np.any(~np.isfinite(coefficients.real)) or np.any(
            ~np.isfinite(coefficients.imag)
        ):
            raise ValueError("coefficients must be finite")
        if not np.any(np.abs(coefficients) > 0.0):
            raise ValueError("at least one coefficient must be nonzero")
        checked_coefficients = np.array(coefficients, copy=True)
        checked_coefficients.setflags(write=False)
        object.__setattr__(self, "carriers", carriers)
        object.__setattr__(self, "coefficients", checked_coefficients)

    @property
    def n_sites(self) -> int:
        return self.carriers[0].n_sites

    @property
    def group_images(self) -> tuple[SitePermutation, ...]:
        return self.carriers[0].group_images

    def component_amplitudes(self, configuration: Sequence[int]) -> np.ndarray:
        return np.asarray(
            [carrier.amplitude(configuration) for carrier in self.carriers],
            dtype=np.complex128,
        )

    def amplitude(self, configuration: Sequence[int]) -> complex:
        return complex(
            np.dot(self.coefficients, self.component_amplitudes(configuration))
        )

    def __call__(self, configuration: Sequence[int]) -> complex:
        return self.amplitude(configuration)

    def hamiltonian_action(
        self,
        configuration: Sequence[int],
        bonds: Iterable[Sequence[float]],
    ) -> complex:
        return heisenberg_hpsi_amplitude(self, configuration, bonds)


def _normalized_graph_bonds(
    n_sites: int, bonds: Iterable[Sequence[float]]
) -> tuple[GraphBond, ...]:
    normalized: list[GraphBond] = []
    for raw in bonds:
        values = tuple(raw)
        if len(values) == 2:
            first, second = values
            coupling = 1.0
        elif len(values) == 3:
            first, second, coupling = values
        else:
            raise ValueError("bonds must contain two sites and an optional coupling")
        if (
            isinstance(first, bool)
            or isinstance(second, bool)
            or not isinstance(first, Integral)
            or not isinstance(second, Integral)
        ):
            raise TypeError("bond sites must be integers")
        first, second = int(first), int(second)
        coupling = float(coupling)
        if first == second or not 0 <= first < n_sites or not 0 <= second < n_sites:
            raise ValueError("bond endpoints must be distinct valid sites")
        if not np.isfinite(coupling):
            raise ValueError("bond couplings must be finite")
        normalized.append((first, second, coupling))
    return tuple(normalized)


def heisenberg_hpsi_amplitude(
    amplitude: SpinAmplitude,
    configuration: Sequence[int],
    bonds: Iterable[Sequence[float]],
) -> complex:
    """Return one exact computational-basis row of ``H @ psi``.

    The graph connectivity obeys ``H[new, old]``.  The spin Heisenberg matrix
    is real symmetric, so the connected column of the requested output config
    also supplies its row without constructing a dense Hilbert-space vector.
    """

    checked = _validated_half_filled_configuration(configuration)
    normalized_bonds = _normalized_graph_bonds(len(checked), bonds)
    operator = SzHeisenbergGraph(
        len(checked), normalized_bonds, n_up=len(checked) // 2
    )
    connected, elements = operator.get_conn(checked)
    return complex(
        sum(
            complex(element) * complex(amplitude(source))
            for source, element in zip(connected, elements, strict=True)
        )
    )


@dataclass(frozen=True)
class ExactSmallAGPHeisenbergReference:
    """Exhaustive fixed-``Sz`` state and dense/reference Hamiltonian action."""

    configurations: tuple[SpinConfiguration, ...]
    amplitudes: np.ndarray
    hamiltonian_actions: np.ndarray
    hamiltonian: np.ndarray

    def __post_init__(self) -> None:
        dimension = len(self.configurations)
        if self.amplitudes.shape != (dimension,):
            raise ValueError("amplitudes must match the exhaustive basis")
        if self.hamiltonian_actions.shape != (dimension,):
            raise ValueError("hamiltonian_actions must match the exhaustive basis")
        if self.hamiltonian.shape != (dimension, dimension):
            raise ValueError("hamiltonian must act on the exhaustive basis")


def exact_small_heisenberg_reference(
    amplitude: SpinAmplitude,
    n_sites: int,
    bonds: Iterable[Sequence[float]],
    *,
    maximum_dimension: int = 20_000,
) -> ExactSmallAGPHeisenbergReference:
    """Build an independent dense ``H @ psi`` reference through ``Sz`` space."""

    if (
        isinstance(n_sites, bool)
        or not isinstance(n_sites, Integral)
        or int(n_sites) < 2
        or int(n_sites) % 2
    ):
        raise ValueError("n_sites must be a positive even integer")
    if (
        isinstance(maximum_dimension, bool)
        or not isinstance(maximum_dimension, Integral)
        or int(maximum_dimension) < 1
    ):
        raise ValueError("maximum_dimension must be a positive integer")
    n_sites = int(n_sites)
    dimension = comb(n_sites, n_sites // 2)
    if dimension > int(maximum_dimension):
        raise ValueError("fixed-Sz dimension exceeds the exact-small cap")
    normalized_bonds = _normalized_graph_bonds(n_sites, bonds)
    operator = SzHeisenbergGraph(
        n_sites, normalized_bonds, n_up=n_sites // 2
    )
    configurations = operator.basis
    amplitudes = np.asarray(
        [amplitude(configuration) for configuration in configurations],
        dtype=np.complex128,
    )
    hamiltonian = np.asarray(operator.to_dense(), dtype=np.float64)
    actions = hamiltonian @ amplitudes
    for array in (amplitudes, hamiltonian, actions):
        array.setflags(write=False)
    return ExactSmallAGPHeisenbergReference(
        configurations=configurations,
        amplitudes=amplitudes,
        hamiltonian_actions=actions,
        hamiltonian=hamiltonian,
    )


