"""Exact-small controls for locality in two-exchange operator strings.

The routines in this module compare low-rank subspaces generated by physical
Hamiltonian-bond strings with matched graph-scrambled strings.  They contain
no neural-network or ED-target logic: candidate directions are selected only
from the source state, the declared operators, and a common target-blind
subspace.

All second-order candidates are time-reversal-even Jordan products
``J_b J_c (h_c h_b + h_b h_c)``.  Repeated bonds are deliberately absent:
for spin one half, ``h_b**2 = 3 I / 16 - h_b / 2`` and hence they add no
direction beyond K0/K1.  Moreover, for three distinct sites,
``{h_ij, h_jk} = h_ik / 2``.  The connected catalogue therefore tests whether
the geometry-selected *induced outer-endpoint exchanges* form a compact
residual coordinate; it must not be described as a generic theorem about all
connected operator strings.
"""

from __future__ import annotations

from collections import Counter, deque
from dataclasses import dataclass
from numbers import Real
from typing import Mapping, Sequence

import numpy as np


@dataclass(frozen=True)
class ExchangeBond:
    """One bare exchange operator and its physical metadata."""

    index: int
    sites: tuple[int, int]
    shell: str
    coupling: float


@dataclass(frozen=True)
class ExchangePair:
    """One unordered pair of distinct exchange bonds."""

    first: int
    second: int
    shell_pair: tuple[str, str]
    shared_sites: tuple[int, ...]
    separation: int | None = None

    @property
    def connected(self) -> bool:
        """Whether the two bonds share at least one physical site."""

        return bool(self.shared_sites)


def _validated_permutation(image: Sequence[int], n_sites: int) -> tuple[int, ...]:
    values = tuple(int(site) for site in image)
    if len(values) != n_sites or tuple(sorted(values)) != tuple(range(n_sites)):
        raise ValueError("image must be a permutation of all physical sites")
    return values


def validate_exchange_bonds(
    bonds: Sequence[ExchangeBond], *, n_sites: int | None = None
) -> tuple[ExchangeBond, ...]:
    """Validate and canonically orient a dense-index exchange catalogue."""

    if not bonds:
        raise ValueError("at least one exchange bond is required")
    checked: list[ExchangeBond] = []
    seen_edges: set[tuple[int, int]] = set()
    for expected, raw in enumerate(bonds):
        if int(raw.index) != expected:
            raise ValueError("bond indices must be dense and agree with list order")
        first, second = (int(raw.sites[0]), int(raw.sites[1]))
        if first == second or min(first, second) < 0:
            raise ValueError("each bond must join distinct non-negative sites")
        if n_sites is not None and max(first, second) >= int(n_sites):
            raise ValueError("bond endpoint lies outside n_sites")
        edge = tuple(sorted((first, second)))
        if edge in seen_edges:
            raise ValueError("exchange catalogue contains a duplicate edge")
        seen_edges.add(edge)
        shell = str(raw.shell)
        if not shell:
            raise ValueError("shell labels must be nonempty")
        coupling = float(raw.coupling)
        if not np.isfinite(coupling) or coupling == 0.0:
            raise ValueError("couplings must be finite and nonzero")
        checked.append(ExchangeBond(expected, edge, shell, coupling))
    return tuple(checked)


def permute_exchange_bonds(
    bonds: Sequence[ExchangeBond], image: Sequence[int], *, n_sites: int
) -> tuple[ExchangeBond, ...]:
    """Apply an active ``old_site -> new_site`` map while retaining labels."""

    checked = validate_exchange_bonds(bonds, n_sites=n_sites)
    permutation = _validated_permutation(image, n_sites)
    return validate_exchange_bonds(
        tuple(
            ExchangeBond(
                bond.index,
                tuple(sorted((permutation[bond.sites[0]], permutation[bond.sites[1]]))),
                bond.shell,
                bond.coupling,
            )
            for bond in checked
        ),
        n_sites=n_sites,
    )


def permutation_commutes_with_group(
    image: Sequence[int], group: Sequence[Sequence[int]]
) -> bool:
    """Return whether a site map centralizes every supplied active group map."""

    if not group:
        raise ValueError("group must be nonempty")
    n_sites = len(tuple(group[0]))
    permutation = _validated_permutation(image, n_sites)
    checked_group = tuple(_validated_permutation(element, n_sites) for element in group)
    return all(
        all(
            permutation[element[site]] == element[permutation[site]]
            for site in range(n_sites)
        )
        for element in checked_group
    )


def weighted_graph_is_automorphism(
    bonds: Sequence[ExchangeBond], image: Sequence[int], *, n_sites: int
) -> bool:
    """Return whether ``image`` preserves every edge shell and coupling."""

    checked = validate_exchange_bonds(bonds, n_sites=n_sites)
    transformed = permute_exchange_bonds(checked, image, n_sites=n_sites)

    def record(items: Sequence[ExchangeBond]) -> set[tuple[tuple[int, int], str, float]]:
        return {(bond.sites, bond.shell, bond.coupling) for bond in items}

    return record(checked) == record(transformed)


def connected_pair_catalog(
    bonds: Sequence[ExchangeBond], *, n_sites: int | None = None
) -> tuple[ExchangePair, ...]:
    """Return every unordered distinct pair whose two bonds share a site."""

    checked = validate_exchange_bonds(bonds, n_sites=n_sites)
    pairs = []
    for first in range(len(checked)):
        for second in range(first + 1, len(checked)):
            shared = tuple(
                sorted(set(checked[first].sites) & set(checked[second].sites))
            )
            if shared:
                pairs.append(
                    ExchangePair(
                        first,
                        second,
                        tuple(sorted((checked[first].shell, checked[second].shell))),
                        shared,
                    )
                )
    return tuple(pairs)


def pair_shell_histogram(
    pairs: Sequence[ExchangePair],
) -> dict[tuple[str, str], int]:
    """Count unordered shell pairs in deterministic key order."""

    counts = Counter(tuple(pair.shell_pair) for pair in pairs)
    return {key: int(counts[key]) for key in sorted(counts)}


def _shortest_path_distances(
    n_sites: int, edges: Sequence[tuple[int, int]]
) -> np.ndarray:
    if n_sites < 1:
        raise ValueError("n_sites must be positive")
    adjacency = [set() for _ in range(n_sites)]
    for raw_first, raw_second in edges:
        first, second = int(raw_first), int(raw_second)
        if first == second or min(first, second) < 0 or max(first, second) >= n_sites:
            raise ValueError("distance edge is invalid")
        adjacency[first].add(second)
        adjacency[second].add(first)
    result = np.full((n_sites, n_sites), n_sites + 1, dtype=np.int64)
    for source in range(n_sites):
        result[source, source] = 0
        queue: deque[int] = deque((source,))
        while queue:
            site = queue.popleft()
            for neighbor in adjacency[site]:
                if result[source, neighbor] > result[source, site] + 1:
                    result[source, neighbor] = result[source, site] + 1
                    queue.append(neighbor)
    if np.any(result > n_sites):
        raise ValueError("distance graph must be connected")
    return result


def matched_farthest_disjoint_pairs(
    bonds: Sequence[ExchangeBond],
    target_pairs: Sequence[ExchangePair],
    *,
    n_sites: int,
    distance_edges: Sequence[tuple[int, int]],
) -> tuple[ExchangePair, ...]:
    """Match a shell histogram with deterministic farthest disjoint pairs.

    Separation is the minimum shortest-path distance between endpoints in the
    supplied physical distance graph.  Ties are resolved by dense bond index.
    """

    checked = validate_exchange_bonds(bonds, n_sites=n_sites)
    required = pair_shell_histogram(target_pairs)
    distances = _shortest_path_distances(n_sites, distance_edges)
    pools: dict[tuple[str, str], list[ExchangePair]] = {
        key: [] for key in required
    }
    for first in range(len(checked)):
        for second in range(first + 1, len(checked)):
            if set(checked[first].sites) & set(checked[second].sites):
                continue
            shell_pair = tuple(sorted((checked[first].shell, checked[second].shell)))
            if shell_pair not in pools:
                continue
            separation = min(
                int(distances[left, right])
                for left in checked[first].sites
                for right in checked[second].sites
            )
            pools[shell_pair].append(
                ExchangePair(first, second, shell_pair, (), separation)
            )
    selected: list[ExchangePair] = []
    for shell_pair in sorted(required):
        ordered = sorted(
            pools[shell_pair],
            key=lambda pair: (-int(pair.separation or 0), pair.first, pair.second),
        )
        count = required[shell_pair]
        if len(ordered) < count:
            raise ValueError(
                f"not enough disjoint {shell_pair} pairs: {len(ordered)} < {count}"
            )
        selected.extend(ordered[:count])
    result = tuple(selected)
    if pair_shell_histogram(result) != required:
        raise RuntimeError("disjoint shell matching failed")
    return result


def jordan_action_matrix(
    initial: np.ndarray,
    local_operators: Sequence[object],
    bonds: Sequence[ExchangeBond],
    pairs: Sequence[ExchangePair],
    *,
    projector: object | None = None,
) -> np.ndarray:
    """Return weighted, time-reversal-even two-exchange action columns."""

    vector = np.asarray(initial, dtype=np.complex128)
    if vector.ndim != 1 or vector.size == 0 or np.any(~np.isfinite(vector)):
        raise ValueError("initial must be a finite nonempty vector")
    checked = validate_exchange_bonds(bonds)
    operators = tuple(local_operators)
    if len(operators) != len(checked):
        raise ValueError("one local operator is required for every bond")
    for index, operator in enumerate(operators):
        if getattr(operator, "shape", None) != (vector.size, vector.size):
            raise ValueError(f"local operator {index} has the wrong shape")
    if projector is not None and getattr(projector, "shape", None) != (
        vector.size,
        vector.size,
    ):
        raise ValueError("projector has the wrong shape")
    first_actions = tuple(
        np.asarray(operator @ vector, dtype=np.complex128) for operator in operators
    )
    columns = []
    for pair in pairs:
        first, second = int(pair.first), int(pair.second)
        if not (0 <= first < second < len(checked)):
            raise ValueError("pair indices must satisfy 0 <= first < second")
        expected_shells = tuple(sorted((checked[first].shell, checked[second].shell)))
        if tuple(pair.shell_pair) != expected_shells:
            raise ValueError("pair shell metadata disagrees with its bonds")
        expected_shared = tuple(
            sorted(set(checked[first].sites) & set(checked[second].sites))
        )
        if tuple(pair.shared_sites) != expected_shared:
            raise ValueError("pair incidence metadata disagrees with its bonds")
        forward = np.asarray(
            operators[second] @ first_actions[first], dtype=np.complex128
        )
        reverse = np.asarray(
            operators[first] @ first_actions[second], dtype=np.complex128
        )
        column = checked[first].coupling * checked[second].coupling * (
            forward + reverse
        )
        if projector is not None:
            column = np.asarray(projector @ column, dtype=np.complex128)
        columns.append(column)
    if not columns:
        return np.zeros((vector.size, 0), dtype=np.complex128)
    return np.column_stack(columns)


def normalized_column_span(
    columns: np.ndarray | Sequence[np.ndarray], *, relative_tolerance: Real = 1e-11
) -> tuple[np.ndarray, dict[str, object]]:
    """Return a rank-revealed orthonormal span after column normalization."""

    tolerance = float(relative_tolerance)
    if not np.isfinite(tolerance) or not 0.0 < tolerance < 1.0:
        raise ValueError("relative_tolerance must lie strictly between zero and one")
    matrix = np.asarray(columns, dtype=np.complex128)
    if matrix.ndim == 1:
        matrix = matrix[:, None]
    if matrix.ndim != 2 or matrix.shape[0] == 0 or matrix.shape[1] == 0:
        raise ValueError("columns must be a nonempty vector or matrix")
    if np.any(~np.isfinite(matrix)):
        raise ValueError("columns must be finite")
    norms = np.linalg.norm(matrix, axis=0)
    # Column scale has no mathematical meaning here: every nonzero column is
    # normalized independently before the rank reveal.  A global max-norm
    # threshold would incorrectly delete a valid direction merely because a
    # different column was assigned larger units.
    active = norms > 0.0
    if not np.any(active):
        raise ValueError("all columns are numerically zero")
    normalized = matrix[:, active] / norms[active][None, :]
    left, singular, _ = np.linalg.svd(normalized, full_matrices=False)
    rank = int(np.count_nonzero(singular > tolerance * singular[0]))
    basis = left[:, :rank]
    identity = np.eye(rank, dtype=np.complex128)
    return basis, {
        "candidate_count": int(matrix.shape[1]),
        "active_candidate_count": int(np.count_nonzero(active)),
        "rank": rank,
        "singular_values": singular.tolist(),
        "condition_number": float(singular[0] / singular[rank - 1]),
        "orthonormality_error": float(
            np.max(np.abs(basis.conj().T @ basis - identity), initial=0.0)
        ),
    }


def fixed_rank_residual_basis(
    common_basis: np.ndarray,
    candidate_columns: np.ndarray,
    incremental_rank: int,
    *,
    relative_tolerance: Real = 1e-11,
) -> tuple[np.ndarray, dict[str, object]]:
    """Select a target-blind fixed-rank augmentation after removing ``Q0``."""

    if isinstance(incremental_rank, bool) or not isinstance(
        incremental_rank, (int, np.integer)
    ) or int(incremental_rank) < 1:
        raise ValueError("incremental_rank must be a positive integer")
    common = np.asarray(common_basis, dtype=np.complex128)
    candidates = np.asarray(candidate_columns, dtype=np.complex128)
    if common.ndim != 2 or common.shape[0] == 0 or common.shape[1] == 0:
        raise ValueError("common_basis must be a nonempty matrix")
    if candidates.ndim != 2 or candidates.shape[0] != common.shape[0]:
        raise ValueError("candidate_columns must share the common row dimension")
    common_error = float(
        np.max(
            np.abs(common.conj().T @ common - np.eye(common.shape[1])), initial=0.0
        )
    )
    if common_error > 1e-9:
        raise ValueError("common_basis must be orthonormal")
    if candidates.shape[1] == 0 or np.any(~np.isfinite(candidates)):
        raise ValueError("candidate_columns must be finite and nonempty")

    raw_norms = np.linalg.norm(candidates, axis=0)
    raw_active = raw_norms > 0.0
    normalized = candidates[:, raw_active] / raw_norms[raw_active][None, :]
    residual = normalized - common @ (common.conj().T @ normalized)
    residual_norms = np.linalg.norm(residual, axis=0)
    residual_active = residual_norms > float(relative_tolerance)
    if not np.any(residual_active):
        return np.zeros((common.shape[0], 0), dtype=np.complex128), {
            "requested_rank": int(incremental_rank),
            "available_rank": 0,
            "selected_rank": 0,
            "rank_satisfied": False,
            "raw_candidate_count": int(candidates.shape[1]),
            "raw_active_count": int(np.count_nonzero(raw_active)),
            "residual_active_count": 0,
            "residual_norm_minimum": 0.0,
            "residual_norm_quantiles": [],
            "singular_values": [],
            "relative_boundary_gap": 0.0,
            "common_orthonormality_error": common_error,
            "common_overlap_error": 0.0,
            "augmentation_orthonormality_error": 0.0,
        }
    quotient = residual[:, residual_active] / residual_norms[residual_active][None, :]
    active_residual_norms = residual_norms[residual_active]
    left, singular, _ = np.linalg.svd(quotient, full_matrices=False)
    tolerance = float(relative_tolerance)
    available = int(np.count_nonzero(singular > tolerance * singular[0]))
    selected = min(int(incremental_rank), available)
    augmentation = left[:, :selected]
    if available > int(incremental_rank):
        boundary_gap = float(
            (singular[incremental_rank - 1] - singular[incremental_rank])
            / singular[incremental_rank - 1]
        )
    elif available == int(incremental_rank):
        boundary_gap = 1.0
    else:
        boundary_gap = 0.0
    identity = np.eye(selected, dtype=np.complex128)
    return augmentation, {
        "requested_rank": int(incremental_rank),
        "available_rank": available,
        "selected_rank": selected,
        "rank_satisfied": available >= int(incremental_rank),
        "raw_candidate_count": int(candidates.shape[1]),
        "raw_active_count": int(np.count_nonzero(raw_active)),
        "residual_active_count": int(np.count_nonzero(residual_active)),
        "residual_norm_minimum": float(np.min(active_residual_norms)),
        "residual_norm_quantiles": np.quantile(
            active_residual_norms, (0.0, 0.1, 0.5, 0.9, 1.0)
        ).tolist(),
        "singular_values": singular.tolist(),
        "relative_boundary_gap": boundary_gap,
        "common_orthonormality_error": common_error,
        "common_overlap_error": float(
            np.max(np.abs(common.conj().T @ augmentation), initial=0.0)
        ),
        "augmentation_orthonormality_error": float(
            np.max(
                np.abs(augmentation.conj().T @ augmentation - identity), initial=0.0
            )
        ),
    }


def ritz_ground_state(
    hamiltonian: object,
    basis: np.ndarray,
    *,
    hermiticity_tolerance: Real = 1e-10,
) -> tuple[np.ndarray, dict[str, float | int]]:
    """Return the lowest Ritz vector in an explicitly orthonormal basis."""

    vectors = np.asarray(basis, dtype=np.complex128)
    if vectors.ndim != 2 or vectors.shape[0] == 0 or vectors.shape[1] == 0:
        raise ValueError("basis must be a nonempty matrix")
    if getattr(hamiltonian, "shape", None) != (vectors.shape[0], vectors.shape[0]):
        raise ValueError("hamiltonian and basis dimensions disagree")
    identity = np.eye(vectors.shape[1], dtype=np.complex128)
    orthonormality = float(
        np.max(np.abs(vectors.conj().T @ vectors - identity), initial=0.0)
    )
    if orthonormality > 1e-9:
        raise ValueError("basis must be orthonormal")
    applied_basis = np.asarray(hamiltonian @ vectors, dtype=np.complex128)
    projected = vectors.conj().T @ applied_basis
    antihermitian = float(np.max(np.abs(projected - projected.conj().T), initial=0.0))
    tolerance = float(hermiticity_tolerance)
    if not np.isfinite(tolerance) or tolerance <= 0.0:
        raise ValueError("hermiticity_tolerance must be finite and positive")
    if antihermitian > tolerance:
        raise RuntimeError("projected Hamiltonian is not Hermitian")
    projected = 0.5 * (projected + projected.conj().T)
    eigenvalues, eigenvectors = np.linalg.eigh(projected)
    state = np.asarray(vectors @ eigenvectors[:, 0], dtype=np.complex128)
    state /= np.linalg.norm(state)
    applied = np.asarray(hamiltonian @ state, dtype=np.complex128)
    rayleigh = complex(np.vdot(state, applied))
    if abs(rayleigh.imag) > tolerance:
        raise RuntimeError("Ritz Rayleigh quotient has a non-negligible imaginary part")
    energy = float(rayleigh.real)
    residual = applied - energy * state
    return state, {
        "rank": int(vectors.shape[1]),
        "energy": energy,
        "variance": float(np.vdot(residual, residual).real),
        "full_residual_norm": float(np.linalg.norm(residual)),
        "projected_ritz_residual": float(np.linalg.norm(vectors.conj().T @ residual)),
        "basis_orthonormality_error": orthonormality,
        "projected_hamiltonian_antihermitian_error": antihermitian,
    }


def residual_reference_capture(
    reference: np.ndarray,
    common_basis: np.ndarray,
    augmentation_basis: np.ndarray,
) -> dict[str, float]:
    """Score target capture only after target-blind subspaces are fixed."""

    target = np.asarray(reference, dtype=np.complex128)
    common = np.asarray(common_basis, dtype=np.complex128)
    augmentation = np.asarray(augmentation_basis, dtype=np.complex128)
    if target.ndim != 1 or common.ndim != 2 or augmentation.ndim != 2:
        raise ValueError("reference and bases have invalid dimensions")
    if target.shape[0] != common.shape[0] or target.shape[0] != augmentation.shape[0]:
        raise ValueError("reference and bases must share a row dimension")
    common_error = float(
        np.max(
            np.abs(common.conj().T @ common - np.eye(common.shape[1])), initial=0.0
        )
    )
    augmentation_error = float(
        np.max(
            np.abs(
                augmentation.conj().T @ augmentation
                - np.eye(augmentation.shape[1])
            ),
            initial=0.0,
        )
    )
    mutual_error = float(
        np.max(np.abs(common.conj().T @ augmentation), initial=0.0)
    )
    if max(common_error, augmentation_error, mutual_error) > 1e-9:
        raise ValueError("common and augmentation bases must be mutually orthonormal")
    norm = float(np.linalg.norm(target))
    if not np.isfinite(norm) or norm <= 0.0:
        raise ValueError("reference must have finite nonzero norm")
    target = target / norm
    residual = target - common @ (common.conj().T @ target)
    denominator = float(np.vdot(residual, residual).real)
    numerator = float(np.linalg.norm(augmentation.conj().T @ residual) ** 2)
    capture = numerator / denominator if denominator > 0.0 else 0.0
    if capture > 1.0 + 1e-9:
        raise RuntimeError("orthogonal-subspace capture exceeds one")
    return {
        "remaining_reference_norm_squared": denominator,
        "captured_norm_squared": numerator,
        "capture_fraction": capture,
    }


