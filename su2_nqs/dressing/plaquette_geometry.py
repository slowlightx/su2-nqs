"""Ordered four-site cells for real-space intertwiner dressing.

The order is part of a gate specification: spatial symmetries move every
entry of an ordered tuple and must not silently sort the result.  This is
essential because the continuous real SU(2)-scalar generators are oriented
chirality/commutator directions rather than permutation-invariant scalars.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence


OrderedPlaquette = tuple[int, int, int, int]


def _site(row: int, column: int, columns: int) -> int:
    return row * columns + column


def square_plaquettes(rows: int, columns: int) -> tuple[OrderedPlaquette, ...]:
    """Return row-major oriented elementary square cells for OBC geometry."""

    if rows < 1 or columns < 1:
        raise ValueError("rows and columns must be positive")
    return tuple(
        (
            _site(row, column, columns),
            _site(row, column + 1, columns),
            _site(row + 1, column, columns),
            _site(row + 1, column + 1, columns),
        )
        for row in range(rows - 1)
        for column in range(columns - 1)
    )


def triangular_rhombi(
    rows: int, columns: int
) -> tuple[OrderedPlaquette, ...]:
    """Return all elementary four-site rhombi of an OBC triangular patch.

    Coordinates follow the repository's 120-degree convention.  Rhombi are
    generated by the three unordered pairs of nearest-neighbor directions
    ``(1,0)``, ``(0,1)``, and ``(1,1)``.  A 3x4 patch therefore has 13 cells.
    """

    if rows < 1 or columns < 1:
        raise ValueError("rows and columns must be positive")
    directions = ((1, 0), (0, 1), (1, 1))
    result: list[OrderedPlaquette] = []
    for first_index, first in enumerate(directions):
        for second in directions[first_index + 1 :]:
            for row in range(rows):
                for column in range(columns):
                    coordinates = (
                        (row, column),
                        (row + first[0], column + first[1]),
                        (row + second[0], column + second[1]),
                        (
                            row + first[0] + second[0],
                            column + first[1] + second[1],
                        ),
                    )
                    if all(
                        0 <= rr < rows and 0 <= cc < columns
                        for rr, cc in coordinates
                    ):
                        result.append(
                            tuple(
                                _site(rr, cc, columns) for rr, cc in coordinates
                            )
                        )
    if len({frozenset(cell) for cell in result}) != len(result):
        raise RuntimeError("triangular rhombus generator produced duplicate cells")
    return tuple(result)


def symmetry_expand_ordered_plaquettes(
    plaquettes: Sequence[Sequence[int]],
    site_permutations: Mapping[str, Sequence[int]] | Sequence[Sequence[int]],
) -> tuple[OrderedPlaquette, ...]:
    """Close ordered cells under active physical-site permutations."""

    raw_images = (
        tuple(site_permutations.values())
        if isinstance(site_permutations, Mapping)
        else tuple(site_permutations)
    )
    if not raw_images:
        raise ValueError("at least one site permutation is required")
    images = tuple(tuple(int(value) for value in image) for image in raw_images)
    n_sites = len(images[0])
    if any(
        len(image) != n_sites or tuple(sorted(image)) != tuple(range(n_sites))
        for image in images
    ):
        raise ValueError("site_permutations must be equal-size permutations")
    checked = tuple(tuple(int(site) for site in cell) for cell in plaquettes)
    if any(
        len(cell) != 4
        or len(set(cell)) != 4
        or any(not 0 <= site < n_sites for site in cell)
        for cell in checked
    ):
        raise ValueError("plaquettes must be ordered distinct in-range quartets")
    expanded = {
        tuple(image[site] for site in cell) for image in images for cell in checked
    }
    return tuple(sorted(expanded))


